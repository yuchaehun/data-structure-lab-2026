"""
그래프 탐색 알고리즘(BFS 및 DFS) 구현 모듈.

이 모듈은 딕셔너리(Dictionary) 형태로 표현된 인접 리스트(Adjacency List) 그래프를 입력받아,
너비 우선 탐색(BFS)과 깊이 우선 탐색(DFS)을 수행합니다.
문제의 특수 조건에 따라, 동일한 깊이(레벨) 또는 분기점에서는 '번호가 작은 노드'를 먼저 방문하도록 설계되었습니다.
"""

from collections import deque

# 그래프의 인접 리스트(Adjacency List) 표현
# 키(Key)는 현재 노드, 값(Value)은 연결된 인접 노드들의 리스트입니다.
A = {
    0: [1, 2, 3],
    1: [0, 2, 4, 5],
    2: [0, 1, 6],
    3: [0],
    4: [1],
    5: [1],
    6: [2]
}

def bfs(A):
    """
    주어진 그래프에 대해 너비 우선 탐색(BFS)을 수행합니다.

    큐(Queue) 자료구조를 활용하여 시작 노드와 가까운 노드부터 레벨 단위로 탐색합니다.
    동일 레벨에서는 노드 번호가 작은 순서대로 방문하도록 설계되었습니다.

    Args:
        A: 탐색할 그래프의 인접 리스트. (Key: 노드 번호, Value: 인접 노드 리스트)

    Returns:
        BFS 알고리즘에 의해 방문된 노드들의 순차적 리스트.
    """
    # 탐색 순서대로 방문한 노드를 저장할 결과 리스트를 초기화합니다.
    answer = []
    
    # [자료구조 선택] 큐(Queue)는 먼저 들어간 데이터가 먼저 나오는 FIFO(선입선출) 구조입니다.
    # 파이썬 기본 리스트의 pop(0)는 시간 복잡도가 O(N)이므로 비효율적입니다.
    # 양방향 입출력이 O(1)로 매우 빠른 collections.deque를 사용하여 큐를 생성하고 시작 노드(0)를 넣습니다.
    queue = deque([0])
    
    # [상태 관리] 방문한 노드를 추적하기 위한 집합(Set)을 생성하고 시작 노드(0)를 기록합니다.
    # 리스트(list) 내 탐색 시간은 O(N)이지만, 집합(set)은 해시 기반이므로 O(1)로 빠릅니다.
    visited = {0} 

    # 큐에 남은 탐색 대상 노드가 없을 때까지(탐색이 완료될 때까지) 반복합니다.
    while queue:
        # 큐의 가장 앞(왼쪽)에 있는 노드를 꺼냅니다.
        node = queue.popleft()
        
        # 꺼낸 노드를 방문 처리하여 결과 리스트에 추가합니다.
        answer.append(node) 

        # [핵심 조건 처리] "작은 번호의 노드부터 방문"
        # 큐는 들어간 순서대로 나오므로(FIFO), 인접 노드를 오름차순(sorted)으로 정렬하여 
        # 작은 번호부터 차례대로 큐에 삽입해야 합니다.
        for neighbor in sorted(A[node]):
            # 인접 노드가 아직 큐에 들어간 적이 없다면 (방문 예정이 아니라면)
            if neighbor not in visited:
                # 중복 삽입을 막기 위해 큐에 넣기 전 즉시 방문 처리를 기록합니다.
                visited.add(neighbor)   
                
                # 큐의 맨 뒤에 인접 노드를 추가하여 다음 탐색 대기열에 올립니다.
                queue.append(neighbor)  

    # 모든 탐색이 끝나면 완성된 방문 순서 리스트를 반환합니다.
    return answer


def dfs(A):
    """
    주어진 그래프에 대해 깊이 우선 탐색(DFS)을 수행합니다.

    스택(Stack) 자료구조를 활용하여 한 경로를 끝까지 탐색한 후 이전 갈림길로 돌아옵니다.
    갈림길에서는 노드 번호가 작은 순서대로 방문하도록 설계되었습니다.

    Args:
        A: 탐색할 그래프의 인접 리스트. (Key: 노드 번호, Value: 인접 노드 리스트)

    Returns:
        DFS 알고리즘에 의해 방문된 노드들의 순차적 리스트.
    """
    # 탐색 순서대로 방문한 노드를 저장할 결과 리스트를 초기화합니다.
    answer = []
    
    # [자료구조 선택] DFS는 나중에 들어간 데이터가 먼저 나오는 스택(Stack, LIFO 구조)을 사용합니다.
    # 파이썬의 기본 리스트는 끝부분 추가(append)와 삭제(pop)가 O(1)이므로 스택으로 쓰기 적합합니다.
    # 시작 노드(0)를 스택에 넣고 시작합니다.
    stack = [0]
    
    # 스택에 동일한 노드가 중복으로 들어가는 것을 막기 위해 방문 처리 집합을 초기화합니다.
    visited = {0} 

    # 스택에 남은 탐색 대상 노드가 없을 때까지 반복합니다.
    while stack:
        # 스택의 가장 위(마지막 위치)에 있는 노드를 꺼냅니다.
        node = stack.pop()
        
        # 꺼낸 노드를 방문 처리하여 결과 리스트에 추가합니다.
        answer.append(node) 

        # [핵심 조건 처리] "작은 번호의 노드부터 방문"
        # 스택은 나중에 넣은 것이 먼저 나오는 후입선출(LIFO) 구조입니다.
        # 따라서 작은 번호를 먼저 꺼내려면, 스택에 넣을 때 '큰 번호'를 먼저 넣고 '작은 번호'를 나중에 넣어야 합니다.
        # 이를 위해 내림차순(reverse=True) 정렬이 필수적입니다.
        for neighbor in sorted(A[node], reverse=True):
            # 인접 노드가 아직 스택에 들어간 적이 없다면
            if neighbor not in visited:
                # 중복 삽입을 막기 위해 스택에 넣기 전 즉시 방문 처리를 기록합니다.
                visited.add(neighbor)    
                
                # 스택의 최상단(리스트의 맨 끝)에 인접 노드를 추가합니다.
                stack.append(neighbor)   

    # 모든 탐색이 끝나면 완성된 방문 순서 리스트를 반환합니다.
    return answer



bfs_result = bfs(A)
dfs_result = dfs(A)

# 아래는 체크함수입니다. 수정하실 필요 없습니다.

print(f"BFS 결과: {bfs_result}")
print(f"DFS 결과: {dfs_result}")
print("-" * 30)

assert bfs_result == [0, 1, 2, 3, 4, 5, 6]
assert dfs_result == [0, 1, 4, 5, 2, 6, 3]

